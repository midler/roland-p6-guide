"""Build the standalone site from src/guide.html.

Usage: python3 tools/build_site.py src/guide.html index.html
Writes index.html and sw.js (offline cache, versioned by content hash).
"""
import hashlib, os, sys

src = open(sys.argv[1], encoding="utf-8").read()
out = sys.argv[2]
i = src.index("<header")
head, body = src[:i], src[i:]
html = '''<!doctype html>
<html lang="ru">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<meta name="description" content="Интерактивный курс по сэмплеру Roland P-6: уроки с точными нажатиями, сетки битов, аккорды, жанровые рецепты.">
<meta name="theme-color" content="#1c1e22">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" href="icon-192.png">
<link rel="apple-touch-icon" href="apple-touch-icon.png">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="P-6">
<style>html{-webkit-text-size-adjust:100%}body{margin:0}img{max-width:100%}[hidden]{display:none!important}</style>
''' + head.strip() + '''
</head>
<body>
''' + body.strip() + '''
<script>
if ("serviceWorker" in navigator && location.protocol.startsWith("http")) {
  window.addEventListener("load", function () { navigator.serviceWorker.register("sw.js").catch(function () {}); });
}
</script>
</body>
</html>
'''
open(out, "w", encoding="utf-8").write(html)

version = hashlib.sha256(html.encode("utf-8")).hexdigest()[:12]
sw = '''// Offline cache for the P-6 guide. Generated by tools/build_site.py.
const CACHE = "p6-%s";
const CORE = ["./", "index.html", "manifest.webmanifest", "icon-192.png", "icon-512.png", "apple-touch-icon.png"];
self.addEventListener("install", e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(CORE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", e => {
  e.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener("fetch", e => {
  const req = e.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  const sameOrigin = url.origin === location.origin;
  const fonts = url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com";
  if (!sameOrigin && !fonts) return;
  e.respondWith(
    caches.open(CACHE).then(async cache => {
      const hit = await cache.match(req, {ignoreSearch: sameOrigin});
      const net = fetch(req).then(res => {
        if (res && (res.status === 200 || res.type === "opaque")) cache.put(req, res.clone()).catch(() => {});
        return res;
      }).catch(() => hit || (req.mode === "navigate" ? cache.match("index.html") : undefined));
      return hit || net;
    })
  );
});
''' % version
open(os.path.join(os.path.dirname(os.path.abspath(out)), "sw.js"), "w", encoding="utf-8").write(sw)
